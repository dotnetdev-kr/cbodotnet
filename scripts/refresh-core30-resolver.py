#!/usr/bin/env python3
"""Refresh the original Core 3.0 XPlat resolver before a new root build process.

The same upstream assembly implements SDK resolution and build metadata tasks.
Build the reviewed current sources at their normal output path and install that
exact DLL before starting the root driver, avoiding mixed same-name assemblies.
"""

import argparse
import datetime
import json
import os
from pathlib import Path
import platform
import runpy
import xml.etree.ElementTree as ET


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir', type=Path, required=True)
    parser.add_argument('--inputs-dir', type=Path, required=True)
    parser.add_argument('--reports-dir', type=Path, required=True)
    parser.add_argument('--profile', type=Path, required=True)
    args = parser.parse_args()
    if platform.system() != 'Linux' or platform.machine().lower() not in ('aarch64', 'arm64'):
        raise ValueError('Use the native Linux ARM64 build container')
    helpers = Path(__file__).resolve().parent
    bootstrap = runpy.run_path(str(helpers / 'prepare-core30-bootstrap.py'))
    inputs_helper = runpy.run_path(str(helpers / 'core30-inputs.py'))
    directory, ordinary, fingerprint = bootstrap['directory'], bootstrap['ordinary_file'], bootstrap['fingerprint']
    source, inputs, reports = directory(args.source_dir), directory(args.inputs_dir), directory(args.reports_dir)
    report_path = reports / 'core30-resolver-refresh.json'
    if report_path.exists() or report_path.is_symlink():
        raise ValueError('Use a new resolver-refresh report directory')
    before = inputs_helper['bootstrap_use'](source, inputs, args.profile)
    profile = json.loads(ordinary(args.profile).read_text())
    patch_manifest = ordinary(helpers.parent / 'patches/core30/manifest.json')
    manifest = json.loads(patch_manifest.read_text())
    root_specs = [item for item in manifest['patches'] if item['component'] is None]
    final_specs = {item['target']: item for item in root_specs}
    for relative in ['tools-local/tasks/Microsoft.DotNet.SourceBuild.Tasks.XPlat/AddSourceToNuGetConfig.cs',
                     'tools-local/tasks/Microsoft.DotNet.SourceBuild.Tasks.XPlat/WriteRestoreSourceAndVersionProps.cs',
                     'tools-local/init-build.proj']:
        if fingerprint(ordinary(source / relative))['sha256'] != final_specs[relative]['patchedSha256']:
            raise ValueError('The reviewed current bootstrap source patch is absent: ' + relative)
    if profile.get('sdkVersion') != '3.0.103' or manifest['sourceCommit'] != bootstrap['SOURCE_COMMIT']:
        raise ValueError('The selected Core 3.0 graph differs')
    sdk = source / '.dotnet'
    state = inputs / 'bootstrap-state'
    contract = json.loads(ordinary(state / 'core30-bootstrap-contract.json').read_text())
    environment = os.environ.copy()
    environment.update(contract['environment'])
    environment['PATH'] = str(sdk) + os.pathsep + environment.get('PATH', '')
    project = source / bootstrap['RESOLVER_PROJECT']
    built = project.parent / 'bin/Debug/netstandard2.0/Microsoft.DotNet.SourceBuild.Tasks.XPlat.dll'
    installed = sdk / 'sdk/3.0.100/SdkResolvers/SourceBuild.MSBuildSdkResolver/SourceBuild.MSBuildSdkResolver.dll'
    record = {'schemaVersion': 1, 'status': 'running', 'sourceCommit': bootstrap['SOURCE_COMMIT'],
              'startedAtUtc': datetime.datetime.now(datetime.timezone.utc).isoformat(), 'commands': [],
              'before': before, 'patchManifest': dict({'path': str(patch_manifest)}, **fingerprint(patch_manifest)),
              'scope': 'The original reviewed XPlat task project and original resolver-copy target only. No SDK product graph or source metadata target is skipped or fabricated.'}
    try:
        command = [str(sdk / 'dotnet'), str(sdk / 'sdk/3.0.100/MSBuild.dll'), str(project),
                   '/p:Configuration=Debug', '/p:SDK_VERSION=3.0.100', '/p:DotNetBuildFromSource=true',
                   '/p:RestoreSources=https://api.nuget.org/v3/index.json', '/m:2', '/nr:false']
        # Use normal task output/intermediate paths. Separate evaluations load
        # framework-reference imports generated by the preceding restore.
        bootstrap['run'](command + ['/t:Restore', '/bl:' + str(reports / 'resolver-refresh-restore.binlog')],
                         source, environment, reports / 'resolver-refresh-restore.log', record['commands'])
        bootstrap['run'](command + ['/t:Build', '/bl:' + str(reports / 'resolver-refresh-build.binlog')],
                         source, environment, reports / 'resolver-refresh-build.log', record['commands'])
        built_info = fingerprint(ordinary(built))
        namespace = {'m': 'http://schemas.microsoft.com/developer/msbuild/2003'}
        original_init = ET.fromstring(bootstrap['git'](source, 'show', bootstrap['SOURCE_COMMIT'] + ':tools-local/init-build.proj'))
        current_init = ET.parse(str(ordinary(source / 'tools-local/init-build.proj'))).getroot()
        selector = "m:Target[@Name='InstallSourceBuildSdkResolver']"
        if ET.tostring(original_init.find(selector, namespace)) != ET.tostring(current_init.find(selector, namespace)):
            raise ValueError('The original resolver installation target changed')
        bootstrap['run']([str(sdk / 'dotnet'), str(sdk / 'sdk/3.0.100/MSBuild.dll'), str(source / 'tools-local/init-build.proj'),
                          '/t:InstallSourceBuildSdkResolver', '/p:SDK_VERSION=3.0.100', '/p:XPlatSourceBuildTasksAssembly=' + str(built),
                          '/nr:false', '/bl:' + str(reports / 'resolver-refresh-install.binlog')], source, environment,
                         reports / 'resolver-refresh-install.log', record['commands'])
        if fingerprint(ordinary(installed)) != built_info:
            raise ValueError('Installed resolver bytes differ from the actual current upstream XPlat assembly')
        # A fresh process must load both the SDK resolver and an actual task
        # from the normal XPlat path. The task edits only this disposable probe.
        probe_directory = reports / 'resolver-refresh-probe'
        probe_directory.mkdir()
        fixture = probe_directory / 'fixture.txt'
        fixture.write_text('before\n')
        probe = ET.Element('Project', {'Sdk': 'Microsoft.DotNet.Arcade.Sdk/1.0.0-beta.19359.6'})
        ET.SubElement(probe, 'UsingTask', {'AssemblyFile': str(built), 'TaskName': 'ReplaceTextInFile'})
        ET.SubElement(probe, 'UsingTask', {'AssemblyFile': str(built), 'TaskName': 'WriteRestoreSourceAndVersionProps'})
        items = ET.SubElement(probe, 'ItemGroup')
        extra = ET.SubElement(items, 'FlowFixture', {'Include': 'MicrosoftSourceLinkVersion'})
        ET.SubElement(extra, 'Version').text = '%24(MicrosoftSourceLinkCommonPackageVersion)'
        generated_flow = probe_directory / 'generated-flow.props'
        flow_cases = []
        for label, common, expected in [('bootstrap', '', '1.0.0-beta2-19322-03'),
                                        ('source-built', '1.0.0-source-built-fixture', '1.0.0-source-built-fixture')]:
            flow_project = ET.Element('Project')
            properties = ET.SubElement(flow_project, 'PropertyGroup')
            ET.SubElement(properties, 'MicrosoftSourceLinkVersion').text = '1.0.0-beta2-19322-03'
            ET.SubElement(properties, 'MicrosoftSourceLinkCommonPackageVersion').text = common
            ET.SubElement(flow_project, 'Import', {'Project': str(generated_flow)})
            flow_target = ET.SubElement(flow_project, 'Target', {'Name': 'Probe'})
            flow_output = probe_directory / ('flow-' + label + '.txt')
            ET.SubElement(flow_target, 'WriteLinesToFile', {'File': str(flow_output),
                          'Lines': '$(MicrosoftSourceLinkVersion)', 'Overwrite': 'true'})
            flow_path = probe_directory / ('flow-' + label + '.proj')
            ET.ElementTree(flow_project).write(str(flow_path), encoding='utf-8', xml_declaration=True)
            ET.SubElement(items, 'FlowCaseProjects', {'Include': str(flow_path)})
            flow_cases.append((label, flow_output, expected))
        target = ET.SubElement(probe, 'Target', {'Name': 'Probe'})
        ET.SubElement(target, 'ReplaceTextInFile', {'InputFile': str(fixture), 'OldText': 'before', 'NewText': 'after'})
        ET.SubElement(target, 'WriteRestoreSourceAndVersionProps', {'RestoreSources': str(source / 'bin/obj/arm64/Release/blob-feed/packages'),
                      'NuGetPackages': '', 'ExtraProperties': '@(FlowFixture)', 'OutputPath': str(generated_flow)})
        ET.SubElement(target, 'MSBuild', {'Projects': '@(FlowCaseProjects)', 'Targets': 'Probe', 'BuildInParallel': 'false'})
        probe_path = probe_directory / 'probe.proj'
        toolset_location = probe_directory / 'toolset-location.txt'
        ET.ElementTree(probe).write(str(probe_path), encoding='utf-8', xml_declaration=True)
        # Use the original Arcade bootstrap-probe contract. It resolves the
        # SDK without requiring the disposable report directory to be a repo.
        bootstrap['run']([str(sdk / 'dotnet'), str(sdk / 'sdk/3.0.100/MSBuild.dll'), str(probe_path),
                          '/t:__WriteToolsetLocation;Probe', '/p:__ToolsetLocationOutputFile=' + str(toolset_location), '/nr:false',
                          '/v:diag', '/bl:' + str(reports / 'resolver-refresh-probe.binlog')], source, environment,
                         reports / 'resolver-refresh-probe.log', record['commands'])
        if fixture.read_text(encoding='utf-8-sig') != 'after\n':
            raise ValueError('The actual XPlat task did not run in the fresh resolver process')
        if Path(ordinary(toolset_location).read_text(encoding='utf-8-sig').strip()).resolve() != Path(contract['environment']['_InitializeToolset']).resolve():
            raise ValueError('The fresh probe selected a different bootstrap toolset')
        log = (reports / 'resolver-refresh-probe.log').read_text(encoding='utf-8', errors='replace')
        if 'SourceBuiltSdkResolver' not in log or 'ReplaceTextInFile' not in log:
            raise ValueError('The probe did not record both resolver and task loading')
        flow_results = []
        for label, output, expected in flow_cases:
            actual = ordinary(output).read_text(encoding='utf-8-sig').strip()
            if actual != expected:
                raise ValueError('The actual source-version flow probe failed: ' + label)
            flow_results.append({'case': label, 'expectedVersion': expected, 'actualVersion': actual,
                                 'output': dict({'path': str(output)}, **fingerprint(output))})
        record.update({'status': 'passed', 'builtXPlatAssembly': dict({'path': str(built)}, **built_info),
                       'installedResolver': dict({'path': str(installed)}, **fingerprint(installed)),
                       'freshProcessResolverAndTaskProbePassed': True,
                       'sourceLinkBootstrapAndBuiltCommonFlowProbe': flow_results,
                       'after': inputs_helper['bootstrap_use'](source, inputs, args.profile),
                       'productBuildExecuted': False})
    except Exception as error:
        record.update({'status': 'failed', 'error': str(error)})
        raise
    finally:
        record['finishedAtUtc'] = datetime.datetime.now(datetime.timezone.utc).isoformat()
        bootstrap['write_json'](report_path, record)
    print(json.dumps({'status': record['status'], 'report': str(report_path), 'productBuildExecuted': False}))


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, KeyError, ET.ParseError) as error:
        raise SystemExit('error: ' + str(error))
