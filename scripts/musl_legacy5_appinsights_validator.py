def compiler_record(workspace,name,host_roots):
    worker=original_worker();record=worker.compiler_record(workspace,name,host_roots)
    if name!='app':return record
    tasks=worker._tasks(worker.ordinary(workspace)/'output',name);task=next(t for t in tasks if t['context']==record['context'])
    p=worker.policy();options=check_app_command(task,record['commandLine'],p)
    generated=check_generated_metadata(record['sources'],host_roots['/output'],p)
    return dict(**record,closedCompilerOptions=options,policyDerivedGeneratedMetadata=generated)


